#!/usr/bin/env bash
# Generate the Python SDK: spec.json -> overlay (speakeasy) -> title pass -> spec.patched.json -> upcloud_api/.
# Python-specific; openapi-python-client, speakeasy, ruff, jq, and uv come from mise.
# Usage: generate.sh [--force]  (--force overwrites uncommitted upcloud_api/ changes)
set -euo pipefail

spec="generator/openapi/spec.json"
patched_spec="generator/openapi/spec.patched.json"
package="upcloud_api"

case "${1:-}" in
  "") force=0 ;;
  --force) force=1 ;;
  *) echo "Usage: generate.sh [--force]" >&2; exit 2 ;;
esac

[ -f "$spec" ] || { echo "ERROR: missing spec file $spec" >&2; exit 1; }
if [ "$force" = 0 ] && [ -n "$(git status --porcelain -- "$package")" ]; then
  git status --short -- "$package" >&2
  echo "ERROR: $package/ has uncommitted changes; commit them or pass --force" >&2
  exit 1
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# The ruff settings openapi-python-client writes for a generated project (--meta uv).
cat >"$tmp/ruff.toml" <<'EOF'
line-length = 120

[lint]
select = ["F", "I", "UP"]
EOF

echo "Applying OpenAPI overlay..."
speakeasy overlay apply --strict --overlay generator/openapi/overlay.yaml --schema "$spec" --out "$tmp/spec.overlaid.json"
echo "Stripping schema titles..."
uv run python generator/scripts/patch_openapi.py "$tmp/spec.overlaid.json" "$patched_spec"

echo "Generating SDK..."
openapi-python-client generate \
  --path "$patched_spec" \
  --config generator/config/openapi-python-client.yml \
  --custom-template-path generator/templates \
  --output-path "$tmp/$package" \
  --meta none \
  --overwrite

# --meta none skips the PEP 561 marker; write the generator's own content.
printf '# Marker file for PEP 561' >"$tmp/$package/py.typed"

# A JSON string literal is also a valid Python string literal.
spec_version_literal="$(jq -e '.info.version | strings' "$spec")"
cat >"$tmp/$package/spec_version.py" <<EOF
"""Auto-generated by generator/scripts/generate.sh. Do not edit."""

SPEC_VERSION = ${spec_version_literal}
EOF

rm -rf "$package"
cp -R "$tmp/$package" "$package"
echo "Generation complete."
